for idx, lang in enumerate(["en", "ar", "de"]):
    d = {"@@locale": lang}
    for k in sorted(S):
        d[k] = S[k][idx]
        if idx == 0 and k in PLACEHOLDERS:
            d["@" + k] = {"placeholders": {p: {"type": t} for p, t in PLACEHOLDERS[k].items()}}
